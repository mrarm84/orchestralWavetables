float lut_sine[641];

void InitTables() {
  // sin(2 pi i / 512) by rotation, re-synchronized on every quadrant
  const float c = 0.99992470183914454f;   // cos(2 pi / 512)
  const float s = 0.01227153828571993f;   // sin(2 pi / 512)
  float x = 1.0f, y = 0.0f;
  for (int i = 0; i < 641; i++) {
    if ((i & 127) == 0) {
      int q = (i >> 7) & 3;
      x = q == 0 ? 1.0f : q == 2 ? -1.0f : 0.0f;
      y = q == 1 ? 1.0f : q == 3 ? -1.0f : 0.0f;
    }
    lut_sine[i] = y;
    float nx = x * c - y * s;
    y = y * c + x * s;
    x = nx;
  }
}

