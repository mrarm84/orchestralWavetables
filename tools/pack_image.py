#!/usr/bin/env python3
"""Compress the enosc3 RAM image for the loader.

usage: pack_image.py app.bin blob.c

Writes a C file with the raw-deflate-compressed image, its size and an
FNV-1a hash of the uncompressed image (checked by loader/loader.c).
"""

import sys
import zlib


def fnv1a(data):
    h = 0x811C9DC5
    for b in data:
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


def main():
    src, dst = sys.argv[1], sys.argv[2]
    image = open(src, 'rb').read()
    c = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
    blob = c.compress(image) + c.flush()
    # sanity check
    assert zlib.decompress(blob, -15) == image
    lines = []
    for i in range(0, len(blob), 16):
        lines.append('  ' + ', '.join('0x%02x' % b for b in blob[i:i + 16]) + ',')
    with open(dst, 'w', newline='\n') as f:
        f.write('/* generated by tools/pack_image.py from %s */\n' % src)
        f.write('#include <stdint.h>\n\n')
        f.write('const uint32_t enosc3_image_size = %du;\n' % len(image))
        f.write('const uint32_t enosc3_image_hash = 0x%08xu;\n' % fnv1a(image))
        f.write('const uint32_t enosc3_blob_size = %du;\n' % len(blob))
        f.write('const uint8_t enosc3_blob[] = {\n')
        f.write('\n'.join(lines))
        f.write('\n};\n')
    print('image %d bytes -> compressed %d bytes (%.0f%%)' %
          (len(image), len(blob), 100.0 * len(blob) / len(image)))


if __name__ == '__main__':
    main()
